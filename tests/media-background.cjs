const assert=require('node:assert/strict');
const media=require('../ui/media-background.js');
assert.equal(typeof media.playbackSpec,'function','media policy must select actual eco/original variants');
const video={kind:'video',original:'source-720p60.mp4',eco:'cached-480p30.mp4',poster:'poster.png',mode:'eco'};
assert.equal(media.playbackSpec(video,true).source,'cached-480p30.mp4');
assert.equal(media.playbackSpec({...video,mode:'original'},true).source,'source-720p60.mp4');
assert.equal(media.playbackSpec(video,false).source,null,'suspended media must release its decoding source');
assert.equal(media.playbackSpec({kind:'gif',original:'animated.gif',poster:'poster.png'},true).source,'animated.gif');
assert.equal(media.playbackSpec(video,true,{collapsed:true}).source,null);
assert.equal(media.playbackSpec(video,true,{visible:false}).source,null);
assert.equal(media.playbackSpec({...video,eco:null},true).source,null,'missing eco must not silently decode original in eco mode');
assert.equal(media.playbackSpec(undefined,true).source,null);
assert.equal(typeof media.MediaSession,'function');
const element={tagName:'VIDEO',style:{},dataset:{},paused:true,src:'',loads:0,plays:0,pause(){this.paused=true},load(){this.loads++},removeAttribute(name){if(name==='src')this.src=''},play(){this.paused=false;this.plays++;return Promise.resolve()},addEventListener(){}};
const session=new media.MediaSession(element,p=>'asset:'+p);
session.update(media.playbackSpec(video,true));assert.equal(element.src,'asset:cached-480p30.mp4');
session.update(media.playbackSpec({...video,mode:'original'},true));assert.equal(element.src,'asset:source-720p60.mp4');
session.update(media.playbackSpec(video,false));assert.equal(element.src,'');assert.equal(element.paused,true);assert.ok(element.loads>=2);
session.update(media.playbackSpec(video,true));assert.equal(element.src,'asset:cached-480p30.mp4');
session.destroy();assert.equal(element.src,'');
