// Executes recovered FenceBox/WidgetBox menus against isolated fixture state.
window.DeskBoxOwnMenuCheck = async invoke => {
  const wait = ms => new Promise(resolve => setTimeout(resolve,ms));
  const assert = (value,message) => { if (!value) throw new Error(message); };
  const state = () => invoke('get_state');
  const initial = await state();
  const fixture = initial.items.find(i => i.name === 'rename-fixture.txt');
  const saved = JSON.parse(JSON.stringify(initial.config.fences.find(f => f.items.includes(fixture.id))));
  const fence = () => [...document.querySelectorAll('[data-fence]')].find(e => e.dataset.fence === saved.id);
  const entry = label => [...document.querySelectorAll('.pm > .pm-item')].find(e => e.querySelector('.pm-label')?.textContent.trim() === label);
  const dismiss = async () => { document.querySelector('.stage').dispatchEvent(new PointerEvent('pointerdown',{bubbles:true,button:0})); await wait(100); };
  const openFence = async () => { fence().querySelector('header').dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,clientX:innerWidth-2,clientY:innerHeight-2})); await wait(350); };
  const until = async predicate => { for (let n=0;n<40;n++) { if (await predicate()) return; await wait(100); } throw new Error('Own-menu action did not persist'); };
  await wait(400);
  await openFence();
  for (const label of ['重命名','搜索框内文件','样式与外观…','按名称排序','隐藏此框','删除此框']) assert(entry(label),'Fence own-menu missing: '+label);
  assert(!entry('打开所在位置') && !entry('属性'),'File menu wrongly used for fence');
  entry('删除此框').click(); await wait(300);
  const confirmation = entry('删除此框').nextElementSibling;
  assert(confirmation.classList.contains('show') && confirmation.textContent.includes('图标移入「其他」'),'Fence delete confirmation/rehome submenu missing');
  assert((await state()).config.fences.some(f => f.id === saved.id),'Fence delete parent executed without confirmation');
  await dismiss();
  await openFence(); entry(saved.collapsed?'展开':'卷起').click();
  await until(async () => (await state()).config.fences.find(f => f.id === saved.id).collapsed !== saved.collapsed);
  assert(fence().classList.contains('collapsed') !== saved.collapsed,'Fence collapsed rendering wrong');
  await openFence(); entry(saved.collapsed?'卷起':'展开').click();
  await until(async () => (await state()).config.fences.find(f => f.id === saved.id).collapsed === saved.collapsed);
  await openFence(); entry('样式与外观…').click(); await wait(200);
  assert(document.querySelector('.sp')?.textContent.includes(saved.title),'Fence own style panel missing');
  const radius = document.querySelector('.sp input[type="range"][max="28"]');
  assert(radius,'Fence radius control missing'); radius.value='17'; radius.dispatchEvent(new Event('input',{bubbles:true}));
  await until(async () => (await state()).config.fences.find(f => f.id === saved.id).style.radius === 17);
  document.querySelector('.sp .x').click(); await wait(150);
  await openFence(); entry('搜索框内文件').click(); await wait(150);
  const search = fence().querySelector('.title-input.search'); assert(search,'Own fence search input missing');
  search.value='__no_matching_fixture__'; search.dispatchEvent(new Event('input',{bubbles:true})); await wait(100);
  assert(!fence().querySelector('.item'),'Search did not filter own items');
  search.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true})); await wait(150);
  assert(fence().querySelector('.item'),'Search cancel did not restore items');
  await openFence(); entry('重命名').click(); await wait(150);
  const title=fence().querySelector('.title-input:not(.search)'); assert(title && !document.getElementById('deskbox-rename-dialog'),'Fence rename used file rename dialog');
  title.value='框菜单交互验证'; title.dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',bubbles:true}));
  await until(async () => (await state()).config.fences.find(f => f.id === saved.id).title === '框菜单交互验证');
  // Browser-level blur models leaving the editor; no real desktop text is changed.
  title.dispatchEvent(new FocusEvent('blur'));
  await invoke('update_fence',{fence:saved}); await wait(400);
  await invoke('frontend_checks_passed',{checks:['fence_own_menu_entries','fence_delete_confirmation','fence_collapse_expand','fence_style_panel_persists','fence_search_filters','fence_title_rename']});
  const monitor = initial.monitors.find(m => m.primary) || initial.monitors[0];
  const id = await invoke('create_widget',{kind:'clock',origin:[monitor.x+200*monitor.scale,monitor.y+200*monitor.scale]}); await wait(200);
  const widget = () => [...document.querySelectorAll('.widget')].find(e => e.dataset.sid === id);
  assert(widget(),'Clock widget not rendered');
  const openWidget = async () => { widget().dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,clientX:innerWidth-2,clientY:innerHeight-2})); await wait(350); };
  await openWidget(); assert(entry('背景浓度') && entry('移除小组件'),'Widget own menu missing'); assert(!entry('删除到回收站'),'File menu wrongly used for widget');
  entry('背景浓度').click(); await wait(250);
  let submenu=entry('背景浓度').nextElementSibling;
  assert(submenu.classList.contains('show'),'Widget opacity submenu did not expand');
  const rows=[...submenu.querySelectorAll('.pm-item.sub')];
  assert(JSON.stringify(rows.map(e=>e.textContent.trim()))===JSON.stringify(['35%','60%','85%','100%']),'Original widget opacity choices differ');
  rows[1].click(); await until(async () => (await state()).config.widgets.find(w=>w.id===id).style.opacity===0.6);
  assert(!document.querySelector('.pm'),'Widget opacity leaf did not close menu');
  await openWidget(); entry('背景浓度').click(); await wait(250); submenu=entry('背景浓度').nextElementSibling;
  assert(submenu.querySelectorAll('.pm-item.sub')[1].querySelector('.pm-check'),'Saved widget opacity checkmark missing');
  await dismiss(); await openWidget(); entry('移除小组件').click();
  await until(async () => !(await state()).config.widgets.some(w=>w.id===id));
  await invoke('frontend_checks_passed',{checks:['widget_own_menu_entries','widget_opacity_choices','widget_opacity_persists_and_checkmark','widget_remove_leaf']});
};
